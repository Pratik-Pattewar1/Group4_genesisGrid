"""Render reports/modelling_report.md from reports/modelling_metrics.json (Stage 4).

Every number in the report is read from the metrics dictionary produced by ``src.modelling``.
"""

from __future__ import annotations

from pathlib import Path

PRETTY = {"baseline_median": "Median baseline", "ridge": "Ridge regression", "random_forest": "Random forest",
          "hist_gbm": "Histogram gradient boosting", "baseline_prior": "Prior baseline (constant)",
          "logistic": "Logistic regression"}
VARIANT_LABEL = {
    "primary": "Order placement, 14 features (with `order_month`)",
    "primary_no_month": "Order placement without `order_month`",
    "primary_excl_missing_time_train": "Order placement; 1,731-row missing-time block removed from training",
    "primary_excl_missing_festival_train": "Order placement; missing-Festival rows removed from training",
    "dispatch_comparison": "**Comparison only:** + rider age & rating, vehicle, batching, weather, traffic",
    "dispatch_no_rating": "**Comparison only:** as above without rider rating",
}


def f(x, d=3):
    return "—" if x is None else f"{x:.{d}f}"


def pct(x, d=1):
    return "—" if x is None else f"{100 * x:.{d}f}%"


def write_report(m: dict, path: Path) -> None:
    """Write the Stage 4 modelling report."""
    r, c, k = m["regression"], m["classification"], m["clustering"]
    fam, best = r["families_final_config"], r["selected"]
    base = fam["baseline_median"]["test"]["all"]
    sel = fam[best]["test"]["all"]
    c30 = c["gt30"]; bc = c["selected"]; s30 = c30[bc]
    t30 = s30["test_at_f1_threshold"]
    dec = m["feature_decisions"]
    sens = c["threshold_sensitivity"]
    passed = sum(ch["passed"] for ch in m["checks"])
    L: list[str] = []
    a = L.append

    a("# DeliveryIQ — Stage 4 Modelling Report\n")
    a(f"**Generated by:** `src/modelling.py` on {m['run_date']} (runtime {m['runtime_seconds']} s) · **Status:** awaiting owner review  ")
    a("**Every number is read from `reports/modelling_metrics.json`.** The test set was used once, after all "
      "decisions were made on training data.\n")

    a("## 1. Headline results (held-out test set)\n")
    a(f"Test period **{m['split']['test_dates'][0]} → {m['split']['test_dates'][1]}** ({m['split']['test_rows']:,} orders). "
      f"Models trained on **{m['split']['train_dates'][0]} → {m['split']['train_dates'][1]}** ({dec['final_train_rows']:,} orders).\n")
    a("| Task | Selected model | Test result | Baseline |\n|---|---|---|---|")
    a(f"| ETA regression (order placement) | {PRETTY[best]} | MAE **{sel['MAE']:.2f} min** · RMSE {sel['RMSE']:.2f} · R² **{sel['R2']:.3f}** "
      f"| median: MAE {base['MAE']:.2f} · RMSE {base['RMSE']:.2f} · R² {base['R2']:.3f} |")
    a(f"| Late risk, > 30 min (project benchmark) | {PRETTY[bc]} | ROC-AUC **{t30['ROC_AUC']:.3f}** · PR-AUC **{t30['PR_AUC']:.3f}** · "
      f"precision {t30['precision']:.3f} · recall {t30['recall']:.3f} · F1 {t30['F1']:.3f} (threshold {t30['threshold']:.3f}) "
      f"| prior: ROC-AUC 0.500 · PR-AUC {t30['prevalence']:.3f} (= prevalence) |")
    a(f"| Delivery zones | K-Means, k = {k['k_selected']} | silhouette **{k['silhouette_selected']:.3f}** | — |\n")
    a(f"The ETA model cuts test MAE by **{100 * (1 - sel['MAE'] / base['MAE']):.1f}%** against the median baseline "
      f"({base['MAE'] - sel['MAE']:.2f} min per order). It explains about {100 * sel['R2']:.0f}% of the variance in delivery time, "
      "using only information available when the order is placed.\n")

    a("## 2. Protocol\n")
    a(f"- **Chronological split** on whole order dates: train ≤ {m['split']['train_dates'][1]}, test ≥ {m['split']['cut_date']} "
      f"({m['split']['train_rows']:,} / {m['split']['test_rows']:,} rows).")
    a(f"- **Tuning and selection on the training split only,** with {len(m['cv_folds'])} forward-chaining CV folds. "
      "Each fold validates on later dates than it trains on:")
    for i, fo in enumerate(m["cv_folds"], 1):
        a(f"  - Fold {i}: train {fo['train_rows']:,} rows → validate {fo['val_rows']:,} rows ({fo['val_dates'][0]} → {fo['val_dates'][1]})")
    a("- **Preprocessing** (median / most-frequent imputation, scaling, one-hot) sits inside each sklearn pipeline, so it is "
      "fitted on training rows only, per fold and for the final model. No missing-indicator columns.")
    a("- **Leakage guard:** inputs only via `get_model_inputs()`; the primary feature sets pass the strict guard. "
      "Comparison models need an explicit `allow_excluded=True` and are labelled as such.")
    a("- **Selection rules:** regression by lowest CV MAE; classification by highest CV PR-AUC; decision threshold by "
      "maximum F1 on out-of-fold training predictions; zones by maximum silhouette.\n")
    a("### `city_code` availability review [owner request]\n")
    a("The dataset has **no independent order-time city field**: the raw `City` column is a city *type*. On geo-valid rows the "
      "city is fully implied by the restaurant coordinates (100% recoverable by nearest centroid), and those are already "
      "features. On the 3,640 geo-invalid rows the rider-ID prefix is the only source, and that is rider-assignment "
      "information. **`city_code` is therefore excluded from the primary model** and added to the leakage guard's excluded list. "
      "The primary set is 14 features.\n")

    a("## 3. Feature-variant decisions (made on training CV only)\n")
    a(f"Rule (pre-registered): {dec['rule']}. Decided with {dec['decided_with']}.\n")
    a("| Variant | Train rows | CV MAE | Test MAE (all) | Test MAE (time present) | Test MAE (time missing) | Test R² |\n|---|---|---|---|---|---|---|")
    for v, d in r["variants"].items():
        a(f"| {VARIANT_LABEL[v]} | {d['train_rows']:,} | {d['cv']['MAE']:.3f} | {d['test']['all']['MAE']:.3f} | "
          f"{d['test']['complete_time']['MAE']:.3f} | {d['test']['missing_time']['MAE']:.3f} | {d['test']['all']['R2']:.3f} |")
    pv = r["variants"]
    a("\n**Decisions:**")
    a(f"- `order_month`: **{'dropped' if dec['drop_order_month'] else 'kept'}**. CV MAE {pv['primary']['cv']['MAE']:.3f} with vs "
      f"{pv['primary_no_month']['cv']['MAE']:.3f} without, so the month adds nothing measurable, and April is never seen in "
      "training.")
    a(f"- Missing-time block (1,731 rows): **{'excluded' if dec['exclude_missing_time_from_training'] else 'kept'} in training**. "
      f"Removing it worsens CV MAE ({pv['primary_excl_missing_time_train']['cv']['MAE']:.3f}) and sharply worsens test error "
      f"on those orders ({pv['primary_excl_missing_time_train']['test']['missing_time']['MAE']:.2f} vs "
      f"{pv['primary']['test']['missing_time']['MAE']:.2f} min).")
    a(f"- Missing-Festival rows (228): **{'excluded' if dec['exclude_missing_festival_from_training'] else 'kept'}**. "
      f"CV MAE {pv['primary_excl_missing_festival_train']['cv']['MAE']:.3f} vs {pv['primary']['cv']['MAE']:.3f}, a "
      f"{100 * (1 - pv['primary_excl_missing_festival_train']['cv']['MAE'] / pv['primary']['cv']['MAE']):.2f}% change, which is "
      "below the 0.5% rule.")
    a(f"- **Final primary feature set ({len(dec['final_features'])}):** {', '.join(f'`{x}`' for x in dec['final_features'])}.\n")

    a("## 4. ETA regression\n")
    a("All models use the final feature set; hyper-parameters were tuned by CV on the primary set.\n")
    a("| Model | Tuned params | CV MAE | CV RMSE | CV R² | Test MAE | Test RMSE | Test R² |\n|---|---|---|---|---|---|---|---|")
    for n, d in fam.items():
        star = " ★" if n == best else ""
        a(f"| {PRETTY[n]}{star} | `{d['params']}` | {d['cv']['MAE']:.3f} | {d['cv']['RMSE']:.3f} | {d['cv']['R2']:.3f} | "
          f"{d['test']['all']['MAE']:.3f} | {d['test']['all']['RMSE']:.3f} | {d['test']['all']['R2']:.3f} |")
    rf = fam["random_forest"]["cv"]["MAE"]
    a(f"\n★ selected by {r['selected_by']}. Random forest is within {abs(rf - fam[best]['cv']['MAE']):.3f} min CV MAE, "
      "a practical tie. Gradient boosting is also lighter to deploy.\n")
    a("Charts: `figures/12_regression_model_comparison.png`, `figures/13_eta_pred_vs_actual.png`.\n")
    a("### Error by segment (test, selected model)\n")
    for col, title in [("traffic_density", "Traffic (evaluation only — not a model input)"), ("city_type", "City type"),
                       ("distance_band", "Distance band"), ("order_time", "Order time")]:
        a(f"**{title}**\n")
        a("| Segment | Orders | MAE | Mean actual |\n|---|---|---|---|")
        for row in r["segments_test"][col]:
            label = str(row[col]).replace("<missing>", "(missing)")    # '<…>' would render as an HTML tag
            a(f"| {label} | {row['n']:,} | {row['MAE']:.3f} | {row['mean_actual']:.2f} |")
        a("")
    worst_tr = max(r["segments_test"]["traffic_density"], key=lambda z: z["MAE"])
    worst_db = max((z for z in r["segments_test"]["distance_band"] if z["distance_band"] != "invalid geo"), key=lambda z: z["MAE"])
    a(f"Chart: `figures/14_eta_error_by_segment.png`. Highest error by traffic: **{worst_tr['traffic_density']}** "
      f"(MAE {worst_tr['MAE']:.2f}); by distance: **{worst_db['distance_band']}** (MAE {worst_db['MAE']:.2f}).\n")
    a("### What drives the predictions (permutation importance; post-hoc on test, not used for any decision)\n")
    a("| Feature | Test MAE increase when shuffled (min) |\n|---|---|")
    for feat, v in r["permutation_importance_test_MAE_increase"].items():
        a(f"| `{feat}` | {v:.4f} |")
    top = list(r["permutation_importance_test_MAE_increase"])[:4]
    a(f"\nTop four: {', '.join(f'`{t}`' for t in top)}. The hour features (`order_hour`, `order_hour_sin/cos`, "
      "`order_time_band`) are collinear with each other, so their importances are split between them.")
    a("Chart: `figures/15_eta_feature_importance.png`.\n")

    a("## 5. Late-delivery classification (> 30 min, project benchmark — not an official SLA)\n")
    a(f"Test prevalence: {pct(t30['prevalence'])}.\n")
    a("| Model | Params | CV ROC-AUC | CV PR-AUC | Threshold | Test precision | Test recall | Test F1 | Test ROC-AUC | Test PR-AUC | Brier |\n|---|---|---|---|---|---|---|---|---|---|---|")
    for n, d in c30.items():
        t = d["test_at_f1_threshold"]
        a(f"| {PRETTY[n]}{' ★' if n == bc else ''} | `{d['params']}` | {d['cv']['ROC_AUC']:.3f} | {d['cv']['PR_AUC']:.3f} | "
          f"{t['threshold']:.3f} | {t['precision']:.3f} | {t['recall']:.3f} | {t['F1']:.3f} | {t['ROC_AUC']:.3f} | {t['PR_AUC']:.3f} | {t['brier']:.3f} |")
    a(f"\n★ selected by {c['selected_by']}. The prior baseline predicts no late orders at 0.5, so its precision, recall and F1 are 0; "
      "this is why accuracy alone is never reported.\n")
    a("### Decision threshold\n")
    ts = s30["threshold_selection_oof"]
    a(f"- **Default: {ts['f1']['threshold']:.3f}**, the F1-maximising threshold on out-of-fold *training* predictions "
      f"(out-of-fold precision {ts['f1']['precision']:.3f}, recall {ts['f1']['recall']:.3f}).")
    a(f"- **Why not 0.5:** {pct(t30['prevalence'], 0)} of test orders are late. A missed late order (no proactive customer message, no "
      "dispatch attention) usually costs more than a false alarm (an unnecessary heads-up). A threshold below 0.5 "
      "trades precision for recall.")
    rt = s30["test_at_recall_threshold"]
    a(f"- **Recall ≥ 80% alternative:** {ts['recall_target']['threshold']:.3f} → test precision {rt['precision']:.3f}, "
      f"recall {rt['recall']:.3f}, F1 {rt['F1']:.3f}" + (". At this benchmark it nearly coincides with the F1 point."
      if abs(ts['recall_target']['threshold'] - ts['f1']['threshold']) < 0.02 else "."))
    cm = t30["confusion"]
    a(f"- **Confusion matrix at the default threshold (test):**")
    a(f"  - {cm['tp']:,} late orders caught; {cm['fn']:,} missed.")
    a(f"  - {cm['fp']:,} false alarms; {cm['tn']:,} correctly cleared.")
    tc = s30["test_complete_time"]
    a(f"- **Orders with an order time** (what the demo sees): ROC-AUC {tc['ROC_AUC']:.3f}, PR-AUC {tc['PR_AUC']:.3f}, F1 {tc['F1']:.3f}.\n")
    a("Charts: `figures/16_classification_roc_pr.png`, `figures/17_classification_threshold.png`, `figures/18_confusion_matrix.png`.\n")
    a("### Benchmark sensitivity (> 30 / > 35 / > 40 min)\n")
    a("Same model family and hyper-parameters; each benchmark gets its own out-of-fold F1 threshold.\n")
    a("| Benchmark | Test prevalence | Threshold | Precision | Recall | F1 | ROC-AUC | PR-AUC | PR-AUC lift |\n|---|---|---|---|---|---|---|---|---|")
    for mins, d in sens.items():
        t = d["test_at_f1_threshold"]
        a(f"| > {mins} min | {pct(t['prevalence'])} | {t['threshold']:.3f} | {t['precision']:.3f} | {t['recall']:.3f} | "
          f"{t['F1']:.3f} | {t['ROC_AUC']:.3f} | {t['PR_AUC']:.3f} | {t['PR_AUC'] / t['prevalence']:.1f}× |")
    a("\nStricter benchmarks give a higher ROC-AUC because very slow orders are easier to rank. But late orders become rarer, "
      "so precision and F1 fall. Chart: `figures/21_late_threshold_sensitivity.png`.\n")
    a("### Feature variants (> 30 min, selected model)\n")
    a("| Variant | CV ROC-AUC | CV PR-AUC | Test ROC-AUC | Test PR-AUC | Test F1 |\n|---|---|---|---|---|---|")
    for v, d in c["variants_gt30"].items():
        a(f"| {VARIANT_LABEL[v]} | {d['cv']['ROC_AUC']:.3f} | {d['cv']['PR_AUC']:.3f} | {d['test']['ROC_AUC']:.3f} | "
          f"{d['test']['PR_AUC']:.3f} | {d['test']['F1']:.3f} |")
    a("")

    a("## 6. Comparison: what dispatch-time information adds (NOT deployable at order placement)\n")
    dc, dn = pv["dispatch_comparison"], pv["dispatch_no_rating"]
    a(f"Adding rider age and rating, vehicle, batching, weather and traffic cuts test MAE from {sel['MAE']:.2f} to "
      f"**{dc['test']['all']['MAE']:.2f} min** (R² {dc['test']['all']['R2']:.3f}). Late-risk ROC-AUC rises to "
      f"{c['variants_gt30']['dispatch_comparison']['test']['ROC_AUC']:.3f}. Without rider rating: MAE {dn['test']['all']['MAE']:.2f}, "
      f"ROC-AUC {c['variants_gt30']['dispatch_no_rating']['test']['ROC_AUC']:.3f}.")
    a("- These fields are excluded from the primary model by owner decision: they are unknown at order placement, or "
      "have unverified recording times or leakage risk.")
    a("- The gap is the value of a **two-stage ETA**: a placement-time estimate, refreshed once a rider is assigned. "
      "That is a Stage 5 recommendation candidate, not a claim about deployable accuracy.")
    a("- Part of the rating effect may be leakage (a rating could include this delivery's feedback), so the no-rating "
      "figures are the safer reference.\n")

    a("## 7. Geographic delivery zones (K-Means)\n")
    a(f"Data: {k['data']} ({k['fit_rows']:,} rows fitted; {k['profiled_rows']:,} profiled). Coordinates projected to km.\n")
    sc = {row["k"]: row for row in k["scan"]}
    a("| k | Inertia (km²) | Silhouette |\n|---|---|---|")
    for kk in [2, 4, 6, 10, 15, 20, 21, 22, 23, 25, 30]:
        if kk in sc:
            a(f"| {kk}{' ★' if kk == k['k_selected'] else ''} | {sc[kk]['inertia']:,.0f} | {sc[kk]['silhouette']:.3f} |")
    a(f"\nSelected **k = {k['k_selected']}** ({k['selected_by']}; silhouette {k['silhouette_selected']:.3f}). The inertia elbow is at "
      f"k = {k['k_elbow']}, but at that point clusters still merge distant cities. Silhouette rises steadily to a sharp peak at "
      f"{k['k_selected']} and then falls. Charts: `figures/19_kmeans_elbow_silhouette.png`, `figures/20_delivery_zones.png`.\n")
    a("| Zone | Orders | Share | Median ETA | Mean ETA | Late > 30 | Mean distance km | Centroid | City (descriptive) |\n|---|---|---|---|---|---|---|---|---|")
    for z in sorted(k["profile"], key=lambda z: -z["late_gt30_pct"]):
        a(f"| {z['zone']} | {z['orders']:,} | {z['share_pct']:.2f}% | {z['median_eta_min']:.1f} | {z['mean_eta_min']:.2f} | "
          f"{z['late_gt30_pct']:.2f}% | {z['mean_distance_km']:.2f} | {z['centroid_lat']:.3f}, {z['centroid_lon']:.3f} | {z['dominant_city_code']} |")
    lates = [z["late_gt30_pct"] for z in k["profile"]]
    a(f"\n**Interpretation:**")
    a(f"- Every zone contains exactly one city code, so the zones are the **{k['k_selected']} cities**. Delivery points are "
      "synthetic offsets around restaurants (Stage 1), so finer intra-city zones are not supported by the data.")
    a(f"- Late rates vary only from {min(lates):.1f}% to {max(lates):.1f}% across zones. **Location explains little of the delay**; "
      "the stronger drivers are in §4's importance table.")
    gi = list(k["geo_invalid_share_by_city"].items())[:3]
    a(f"- **Zone volumes are uneven because invalid locations are concentrated by city.** Overall "
      f"{pct(k['geo_invalid_share_overall'])} of orders have no valid location, but "
      + ", ".join(f"{c} {pct(v)}" for c, v in gi)
      + ". Those cities are under-represented in the zone counts, and their zone profiles rest on fewer orders.")
    a(f"- Rider segmentation: {k['rider_segmentation']}.\n")

    a("## 8. Validation checks\n")
    a("| # | Check | Result | Detail |\n|---|---|---|---|")
    for i, ch in enumerate(m["checks"], 1):
        a(f"| {i} | {ch['check']} | {'✅ pass' if ch['passed'] else '❌ FAIL'} | {ch['detail']} |")
    a(f"\n**{passed} / {len(m['checks'])} passed.**\n")
    pa = m["sanity_permutation_classification_AUC"]
    a(f"**Finding on the label-permutation check:** a first version shuffled the labels once and expected test ROC-AUC near 0.5. "
      "It failed (0.565). Repeating the shuffle showed why:")
    a(f"- Over {pa['runs']} shuffles, AUC averages **{pa['mean']:.3f}** (sd {pa['sd']:.3f}, range {pa['min']:.3f}–{pa['max']:.3f}), "
      f"with {pct(pa['share_above_0.5'], 0)} above 0.5. That is symmetric around 0.5, so no leakage.")
    a("- A model fitted to noise has a random coefficient direction, and a random combination of *informative* features "
      "correlates, positively or negatively, with the true labels.")
    a("- The check now tests the distribution, and requires the real model to beat every shuffled run.\n")

    a("## 9. Limitations\n")
    a(f"- **Modest primary accuracy by design:** without dispatch-time fields, test R² is {sel['R2']:.3f} and the late-risk F1 is {t30['F1']:.3f}. "
      "This is the honest order-placement level of accuracy for this dataset.")
    a("- **Short test window:** 8 days (2022-03-30 → 04-06) inside an 8-week dataset. No seasonality can be assessed, "
      "and all CV folds fall in March.")
    a("- **Synthetic data patterns** (Stage 1): 5-minute target blocks, diagonal delivery offsets, traffic set by hour. "
      "Metrics may not transfer to real operations.")
    a("- **Median imputation** treats the 3,640 geo-invalid and 1,731 missing-time orders as typical orders. Their errors are "
      "higher (see segments).")
    a("- **Models are trained on the training split only** and are not refitted on all data, so the saved models are exactly "
      "the ones evaluated. A production refit on all 45,593 rows would be a separate, documented step.")
    a("- **Hyper-parameters were tuned on the primary set** and reused for the variants and the final set. Variant "
      "comparisons are therefore not fully re-tuned.")
    a("- **Probabilities are not calibrated:** Brier scores are reported; calibration is not checked yet.")
    a("- **The comparison model's rating effect** may include leakage.\n")

    a("## 10. Files\n")
    a("| File | Content |\n|---|---|")
    a("| `models/eta_regressor.joblib` | selected ETA pipeline + feature list |")
    a("| `models/late_classifier_gt30.joblib` / `gt35` / `gt40` | late-risk pipelines + decision thresholds |")
    a("| `models/delivery_zones_kmeans.joblib` | K-Means zones + projection reference |")
    a("| `models/model_card.json` | summary of every saved model |")
    a("| `reports/modelling_metrics.json` | every number in this report |")
    for fg in m["figures"]:
        a(f"| `{fg}` | chart |")
    a("\n```powershell\ncd D:\\Project1\n.venv\\Scripts\\python.exe -m src.modelling\n```")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
